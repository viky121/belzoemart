// Copies apps/web/public/belzo-logo.svg verbatim into src/ui/brand/belzo-logo.generated.ts
// (design §3.3). Run with `pnpm --filter @belzo/mobile brand:sync`. Line endings are normalised
// to LF so the generated module is identical on Windows and Linux checkouts.
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const mobileRoot = resolve(here, '..');
const source = resolve(mobileRoot, '../web/public/belzo-logo.svg');
const target = resolve(mobileRoot, 'src/ui/brand/belzo-logo.generated.ts');

const xml = readFileSync(source, 'utf8').replace(/\r\n/g, '\n');
const out =
  '// GENERATED by scripts/sync-brand.mjs from apps/web/public/belzo-logo.svg. Do not edit.\n' +
  '// Regenerate with `pnpm --filter @belzo/mobile brand:sync`.\n' +
  '// prettier-ignore\n' +
  `export const BELZO_LOGO_XML = ${JSON.stringify(xml)};\n`;

mkdirSync(dirname(target), { recursive: true });
writeFileSync(target, out, 'utf8');
console.log(`brand:sync wrote ${target} (${xml.length} chars)`);
